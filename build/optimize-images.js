/**
 * Optimize images: raster assets → WebP with size profiles for heroes vs cards vs logo.
 * Preserves folder structure under dist/images/
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const srcDir = path.join(__dirname, '..', 'images');
const distDir = path.join(__dirname, '..', 'dist', 'images');

const RASTER_IN = ['.jpg', '.jpeg', '.png', '.webp'];

/** Heroes span full viewport — cap width to reduce bytes while staying sharp on large screens. */
const PROFILE_HERO = { maxWidth: 1680, quality: 78 };
/** Cards / thumbnails — displayed ~≤360px wide even on dense grids. */
const PROFILE_CARD = { maxWidth: 720, quality: 82 };
/** Header logo raster */
const PROFILE_LOGO = { maxWidth: 260, quality: 86 };
/** Tiny icons generated by build — leave small */
const PROFILE_TINY = { maxWidth: 64, quality: 92 };

function getProfile(relPath) {
  const norm = relPath.replace(/\\/g, '/');
  const lower = norm.toLowerCase();
  const base = path.basename(lower);

  if (lower.includes('hero banner')) return PROFILE_HERO;
  if (base === 'logo-nice88.png') return PROFILE_LOGO;
  if (base === 'nice88-favicon.webp') return PROFILE_TINY;

  return PROFILE_CARD;
}

function getAllImageFiles(dir, base = '') {
  const results = [];
  if (!fs.existsSync(dir)) return results;
  const items = fs.readdirSync(dir, { withFileTypes: true });
  for (const item of items) {
    const relPath = path.join(base, item.name);
    const fullPath = path.join(dir, item.name);
    if (item.isDirectory()) {
      results.push(...getAllImageFiles(fullPath, relPath));
      continue;
    }
    const lower = item.name.toLowerCase();
    const ext = path.extname(lower);
    if (!RASTER_IN.includes(ext)) continue;
    if (lower === 'apple-touch-icon.png') continue;

    results.push(relPath);
  }
  return results;
}

async function optimizeImage(srcPath, relPath) {
  const ext = path.extname(relPath).toLowerCase();
  const baseName = path.basename(relPath, ext);
  const dirName = path.dirname(relPath);
  const outDir = path.join(distDir, dirName);
  const outPath = path.join(outDir, `${baseName}.webp`);

  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  const profile = getProfile(relPath);
  const metadata = await sharp(srcPath).metadata();

  let pipeline = sharp(srcPath).rotate();

  if (metadata.width && metadata.width > profile.maxWidth) {
    pipeline = pipeline.resize(profile.maxWidth, null, {
      withoutEnlargement: true,
      fit: 'inside'
    });
  }

  await pipeline.webp({ quality: profile.quality, effort: 5 }).toFile(outPath);
}

async function run() {
  if (!fs.existsSync(srcDir)) {
    console.log('No images folder found, skipping.');
    return;
  }

  const files = getAllImageFiles(srcDir);
  console.log(`Optimizing ${files.length} images to WebP...`);

  for (const relPath of files) {
    const srcPath = path.join(srcDir, relPath);
    try {
      await optimizeImage(srcPath, relPath);
      console.log(`  ✓ ${relPath}`);
    } catch (err) {
      console.error(`  ✗ ${relPath}:`, err.message);
    }
  }

  const svgRel = 'favicon.svg';
  const svgSrc = path.join(srcDir, svgRel);
  const svgDest = path.join(distDir, svgRel);
  if (fs.existsSync(svgSrc)) {
    fs.mkdirSync(path.dirname(svgDest), { recursive: true });
    fs.copyFileSync(svgSrc, svgDest);
    console.log('  ✓ favicon.svg (copied)');
  }

  const atRel = 'apple-touch-icon.png';
  const atSrc = path.join(srcDir, atRel);
  const atDest = path.join(distDir, atRel);
  if (fs.existsSync(atSrc)) {
    fs.mkdirSync(path.dirname(atDest), { recursive: true });
    fs.copyFileSync(atSrc, atDest);
    console.log('  ✓ apple-touch-icon.png (copied)');
  }

  const distRoot = path.join(__dirname, '..', 'dist');
  const ogImageDest = path.join(distRoot, 'og-image.jpg');
  const ogImageSrc = path.join(srcDir, 'Hero Banner', 'Home.jpg');
  if (!fs.existsSync(ogImageDest) && fs.existsSync(ogImageSrc)) {
    try {
      await sharp(ogImageSrc)
        .rotate()
        .resize(1200, 630, { fit: 'cover', position: 'attention' })
        .jpeg({ quality: 88, mozjpeg: true })
        .toFile(ogImageDest);
      console.log('✓ Created og-image.jpg for social sharing');
    } catch (err) {
      console.warn('  Could not create og-image.jpg:', err.message);
    }
  }

  console.log('✓ Image optimization complete.');
}

module.exports = run;
